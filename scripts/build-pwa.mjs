// Generates the PWA files that must be plain static assets:
//   public/sw.js              the service worker (from src/lib/pwa/cache-rules.ts + sw-core.ts)
//   public/offline/{pt,en}.html  the localized offline fallback pages (from src/messages/*.json)
// Runs before `next build` (npm "prebuild"); src/lib/pwa/generated.test.ts fails if the
// committed files drift from their sources. Usage: node scripts/build-pwa.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = ["pt", "en"];

/** Strips types, imports and `export` keywords so the module can be inlined in a classic script. */
function inlineModule(relPath) {
  const source = readFileSync(join(ROOT, relPath), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext, removeComments: false },
    fileName: relPath,
  });
  return outputText
    .replace(/^import\s[\s\S]*?\sfrom\s+["'][^"']+["'];?\s*$/gm, "")
    .replace(/^export\s+(?=(const|let|function|async function|class)\s)/gm, "")
    .replace(/^export\s*\{\s*\};?\s*$/gm, "")
    .trim();
}

const WIRING = `
const worker = createWorker({
  caches: self.caches,
  fetch: (input, init) => self.fetch(input, init),
  origin: self.location.origin,
  language: self.navigator.language,
});

// The waiting phase is never skipped: an updated worker waits until every tab using the old one is closed,
// so an open tab is never switched mid-write. clients.claim() then only takes pages that
// have no worker yet (the very first install), so the first visit is cached too.
self.addEventListener("install", (event) => {
  event.waitUntil(worker.install());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(worker.activate().then(() => self.clients.claim()));
});

self.addEventListener("fetch", (event) => {
  const extend = (promise) => {
    try {
      event.waitUntil(promise);
    } catch (_) {
      // The event already finished; the cache write still runs best-effort.
    }
  };
  const response = worker.handleFetch(event.request, extend);
  if (response) event.respondWith(response);
});

self.addEventListener("message", (event) => {
  event.waitUntil(worker.handleMessage(event.data));
});
`;

function serviceWorker() {
  return [
    "// GENERATED by scripts/build-pwa.mjs from src/lib/pwa/cache-rules.ts and src/lib/pwa/sw-core.ts.",
    "// Do not edit by hand: run `npm run build:pwa`.",
    "(() => {",
    '"use strict";',
    inlineModule("src/lib/pwa/cache-rules.ts"),
    inlineModule("src/lib/pwa/sw-core.ts"),
    WIRING.trim(),
    "})();",
    "",
  ].join("\n");
}

const escapeHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function offlinePage(locale) {
  const { offline } = JSON.parse(readFileSync(join(ROOT, "src", "messages", `${locale}.json`), "utf8"));
  const t = (key) => escapeHtml(offline[key]);
  return `<!doctype html>
<html lang="${locale}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="#2E933C">
<meta name="robots" content="noindex">
<title>${t("title")}</title>
<link rel="icon" href="/icons/icon-192.png">
<style>
  body { margin: 0; min-height: 100vh; display: grid; place-items: center; font-family: system-ui, sans-serif; background: #F4FBF6; color: #1b1f23; }
  main { max-width: 26rem; padding: 1.5rem; text-align: center; }
  img { width: 96px; height: 96px; }
  h1 { font-size: 1.5rem; margin: 1rem 0 0.5rem; }
  p { line-height: 1.5; }
  a { display: inline-flex; align-items: center; justify-content: center; min-height: 44px; min-width: 44px; padding: 0 1.25rem; border-radius: 0.5rem; background: #2E933C; color: #fff; text-decoration: none; font-weight: 600; }
  a:focus-visible { outline: 3px solid #1d6fd8; outline-offset: 2px; }
</style>
</head>
<body>
<main>
<img src="/icons/icon-192.png" alt="" width="96" height="96">
<h1>${t("heading")}</h1>
<p>${t("body")}</p>
<a href="/${locale}/today">${t("retry")}</a>
</main>
</body>
</html>
`;
}

/** All generated files, keyed by path relative to the repo root. */
export function buildPwa() {
  const files = { "public/sw.js": serviceWorker() };
  for (const locale of LOCALES) files[`public/offline/${locale}.html`] = offlinePage(locale);
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [path, content] of Object.entries(buildPwa())) {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), content);
    console.log(`wrote ${path}`);
  }
}
